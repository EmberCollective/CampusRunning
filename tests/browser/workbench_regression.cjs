// Run only against the isolated dashboard fixture server; no real BLE or Keep account.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const [base, output, executablePath] = process.argv.slice(2);
if (!base || !output || !executablePath) throw new Error('Usage: node workbench_regression.cjs URL OUTPUT CHROMIUM');
const root = path.resolve(__dirname, '../..');
if (path.resolve(output).startsWith(root + path.sep)) throw new Error('OUTPUT must be outside the repository');
fs.mkdirSync(output, { recursive: true });
(async () => {
    const browser = await chromium.launch({ executablePath, headless: true });
    const context = await browser.newContext({ viewport: { width: 1440, height: 960 }, acceptDownloads: true });
    const page = await context.newPage(), errors = [], checks = [];
    page.on('pageerror', error => errors.push(error.message));
    const pass = name => { checks.push(name); console.log('PASS', name); };
    const state = () => context.request.get(base + '/api/watch/status').then(r => r.json());
    try {
        await page.goto(base + '/');
        await page.waitForFunction(() => document.querySelectorAll('#track-choice option').length > 1);
        const before = await state();
        assert.equal(before.records.length, 0, 'Use a fresh isolated dashboard fixture with an empty batch');
        await page.locator('[data-mode="dates"]').click();
        await page.locator('#clear-dates').click();
        await page.locator('#calendar-month').fill('2026-10');
        await page.locator('#calendar-month').press('Tab');
        await page.locator('[data-date="2026-10-31"]').click();
        await page.locator('#next-month').click();
        await page.locator('[data-date="2026-11-02"]').click();
        assert.equal(await page.locator('.date-chip').count(), 2);
        await page.locator('#previous-month').click();
        assert.equal(await page.locator('[data-date="2026-10-31"]').getAttribute('aria-pressed'), 'true');
        pass('month jump retains dates across months');
        await page.locator('#min-distance').fill('0.2');
        await page.locator('#max-distance').fill('0.2');
        await page.locator('#min-pace').fill('7.5');
        await page.locator('#max-pace').fill('7.5');
        await page.locator('#output-format').selectOption('b5');
        const response = page.waitForResponse(r => r.url().endsWith('/api/generate/dates'));
        await page.locator('#generate-button').click();
        const generated = await (await response).json();
        await page.waitForFunction(() => !document.querySelector('#result-next').disabled);
        assert.equal(generated.files.length, 2);
        assert(generated.files.every(f => f.filename.endsWith('.sport44')));
        assert.deepEqual((await state()).records, before.records);
        pass('real B5 generation does not load or broadcast');
        await page.locator('#result-next').click();
        await page.waitForFunction(() => !document.querySelector('#load-candidate').disabled);
        assert.equal((await state()).records.length, before.records.length);
        await page.locator('#load-candidate').click();
        await page.waitForFunction(() => document.querySelector('#candidate').hidden);
        assert.equal((await state()).pending, 2);
        await page.waitForFunction(() => !document.querySelector('#copy-address').disabled);
        pass('explicit load reaches the existing protected endpoint');
        await page.locator('[data-filter="received"]').click();
        assert(await page.locator('#empty-records').isVisible());
        await page.locator('[data-filter="pending"]').click();
        assert.equal(await page.locator('#watch-records tr').count(), 2);
        await page.locator('#toggle-broadcast').click();
        await page.waitForFunction(() => document.querySelector('#sample-mac').textContent === '—');
        assert(await page.locator('#copy-address').isDisabled());
        assert(await page.locator('#dialog-copy').isDisabled());
        assert.equal((await state()).records.length, 2);
        pass('stop invalidates address and retains files');
        await page.locator('#toggle-broadcast').click();
        await page.waitForFunction(() => !document.querySelector('#copy-address').disabled);
        pass('start waits for confirmed address');
        await page.route('**/api/watch/status', route => route.abort());
        await page.locator('#retry-status').evaluate(e => e.click());
        await page.waitForFunction(() => document.querySelector('#copy-address').disabled);
        assert.equal(await page.locator('#sample-mac').innerText(), '—');
        assert(await page.locator('#toggle-broadcast').isDisabled());
        assert.equal(await page.locator('#watch-records tr').count(), 2);
        await page.unroute('**/api/watch/status');
        await page.locator('#retry-status').click();
        await page.waitForFunction(() => !document.querySelector('#copy-address').disabled);
        pass('failed reads clear stale address and recover without dropping records');
        await page.locator('#open-settings').click();
        await page.waitForFunction(() => !document.querySelector('#apply-settings').disabled);
        await page.locator('#transport-choice').selectOption('windows');
        assert(await page.locator('#windows-options').isVisible());
        assert(await page.locator('#apply-settings').isDisabled());
        await page.locator('#transport-choice').selectOption('netsim');
        await page.locator('[data-setting-tab="maps"]').click();
        await page.locator('#map-provider').selectOption('fresh');
        await page.locator('#apply-settings').click();
        await page.waitForFunction(() => !document.querySelector('#settings-dialog').open);
        assert.equal((await state()).running, true);
        pass('map settings preserve an active broadcast; future transports remain disabled');
        await page.locator('[data-nav="generate"]').click();
        await page.locator('[data-mode="single"]').click();
        await page.locator('#start-date').fill('2026-11-03');
        await page.locator('#single-distance').fill('0.2');
        const single = page.waitForResponse(r => r.url().endsWith('/api/generate/single'));
        await page.locator('#generate-button').click(); await single;
        await page.waitForFunction(() => !document.querySelector('#result-next').disabled);
        await page.locator('#result-next').click();
        await page.waitForFunction(() => !document.querySelector('#candidate').hidden);
        assert(await page.locator('#load-candidate').isDisabled());
        assert.equal((await state()).records.length, 2);
        pass('pending batch prevents replacement');

        await page.locator('[data-nav="tracks"]').click();
        await page.waitForFunction(() => TrackEditor.isReady() && points.length > 0);
        const initial = await page.evaluate(() => JSON.stringify(points));
        await page.locator('[data-shape="rect"]').click();
        assert.equal(await page.evaluate(() => JSON.stringify(points)), initial);
        assert(await page.locator('#pending-actions').isVisible());
        await page.locator('#cancel-shape').click();
        assert.equal(await page.evaluate(() => JSON.stringify(points)), initial);
        pass('shape preview and cancel preserve original geometry');
        await page.locator('#select-all').click();
        const width = Number(await page.locator('#selection-width').inputValue());
        await page.locator('#selection-width').fill((width + 10).toFixed(1));
        await page.locator('#selection-width').press('Tab');
        assert.notEqual(await page.evaluate(() => JSON.stringify(points)), initial);
        await page.locator('#editor-undo').click();
        assert.equal(await page.evaluate(() => JSON.stringify(points)), initial);
        await page.locator('#select-all').click();
        await page.locator('#rotate-right').click();
        assert.notEqual(await page.evaluate(() => JSON.stringify(points)), initial);
        await page.locator('#editor-undo').click();
        pass('numeric resize and rotation are undoable');
        await page.locator('#track-name').fill('未保存的页面编辑');
        await page.locator('#track-library .track-row').nth(1).click();
        await page.locator('#track-library .track-row').first().click();
        assert.equal(await page.locator('#track-name').inputValue(), '未保存的页面编辑');
        await page.locator('#track-name').fill('默认操场轨迹');
        await page.locator('#editor-shortcuts').click();
        await page.keyboard.press('Control+a');
        assert.deepEqual(await page.evaluate(() => SelectionLayer.indices()), []);
        await page.keyboard.press('Escape');
        assert.equal(await page.locator('#editor-shortcuts').evaluate(e => e === document.activeElement), true);
        pass('switching tracks retains edits; dialogs isolate shortcuts and restore focus');

        // Hold a track fetch while saving the currently displayed geometry.
        const savedId = await page.locator('#track-id').inputValue();
        let delayedRoute, beganFetch;
        const fetchStarted = new Promise(resolve => { beganFetch = resolve; });
        await page.route('**/api/tracks/late-track/coords', route => { delayedRoute = route; beganFetch(); });
        await page.evaluate(() => { window.delayedOpen = TrackEditor.open('late-track'); });
        await fetchStarted;
        await page.locator('#save-track').click();
        await page.waitForFunction(() => !document.querySelector('#save-track').disabled);
        await delayedRoute.fulfill({json:{id:'late-track',name:'Late response',base_coordinates:[{latitude:26.42,longitude:106.67}]}});
        await page.evaluate(() => window.delayedOpen);
        assert.equal(await page.locator('#track-id').inputValue(), savedId);
        assert.equal(await page.evaluate(() => JSON.stringify(points)), initial);
        await page.unroute('**/api/tracks/late-track/coords');
        pass('late track fetch cannot replace geometry during save');

        // Search-service stub checks frontend sequencing without a live map key.
        await page.evaluate(() => {
            window.searchCalls = [];
            _serverAmapKey = 'local-test'; updateSearchState();
            placeSearch = {search(keyword, callback) { window.searchCalls.push({keyword,callback}); }};
        });
        await page.locator('#search-input').fill('first');
        await page.locator('#search-input').press('Enter');
        await page.waitForTimeout(350);
        assert.equal(await page.evaluate(() => window.searchCalls.length), 1);
        await page.locator('#search-input').fill('second');
        await page.locator('#search-input').press('Enter');
        await page.evaluate(() => window.searchCalls[0].callback('no_data', {}));
        assert.equal(await page.locator('#search-results').isVisible(), false);
        await page.evaluate(() => window.searchCalls[1].callback('no_data', {}));
        assert.equal(await page.locator('#search-results').isVisible(), true);
        await page.locator('#search-input').fill('');
        await page.evaluate(() => window.searchCalls[1].callback('no_data', {}));
        assert.equal(await page.locator('#search-results').isVisible(), false);
        await page.evaluate(() => { _serverAmapKey = ''; placeSearch = null; updateSearchState(); });
        pass('Enter searches once; stale search responses stay hidden');

        await page.locator('[data-nav="generate"]').click();
        await page.locator('#template-upload').setInputFiles({name:'import.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({id:'__proto__',name:'<img src=x onerror=alert(1)>',dates_config:{dates:['2026-01-31','2026-02-02'],min_km:2,max_km:3,output_format:'fit'}}))});
        await page.waitForFunction(() => document.querySelector('#template-choice').value === 'local:__proto__');
        assert.equal(await page.locator('#template-choice img').count(), 0);
        assert.equal(await page.locator('.date-chip').count(), 2);
        pass('template import uses text-safe rendering and restores selected dates');
        await page.locator('#save-template').click();
        await page.locator('#template-name').fill('工作台回归');
        const downloadPromise = page.waitForEvent('download');
        await page.locator('#template-form button[type="submit"]').click();
        const download = await downloadPromise;
        await download.saveAs(path.join(output, download.suggestedFilename()));
        assert.equal(JSON.parse(fs.readFileSync(path.join(output, download.suggestedFilename()), 'utf8')).dates_config.dates.length, 2);
        pass('template export retains mode and selected dates');
        assert.deepEqual(errors, []);
        await page.screenshot({path:path.join(output,'final-ui.png'),fullPage:true});
    } finally {
        fs.writeFileSync(path.join(output,'results.json'),JSON.stringify({checks,errors},null,2));
        await browser.close();
    }
})().catch(error => { console.error(error); process.exitCode = 1; });
