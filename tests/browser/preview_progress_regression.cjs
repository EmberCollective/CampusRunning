// Read-only map navigation; watch states below are explicit API fixtures, with no BLE actions.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const [base, output, executablePath] = process.argv.slice(2);
if (!base || !output || !executablePath) throw new Error('Usage: node preview_progress_regression.cjs URL OUTPUT CHROMIUM');
if (path.resolve(output).startsWith(path.resolve(__dirname, '../..') + path.sep)) throw new Error('OUTPUT must be outside the repository');
fs.mkdirSync(output, { recursive: true });
(async () => {
    const browser = await chromium.launch({ executablePath, headless: true });
    const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, reducedMotion: 'reduce' });
    const errors = [], checks = [];
    page.on('pageerror', error => errors.push(error.message));
    const pass = name => { checks.push(name); console.log('PASS', name); };
    await page.route('**/map_adapter_leaflet.js', async route => {
        const response = await route.fetch();
        await route.fulfill({response, body:await response.text() + '\nL.Map.addInitHook(function () { if (this.getContainer().id === "preview-map") window.__previewMap = this; });'});
    });
    const view = () => page.evaluate(() => ({zoom:__previewMap.getZoom(), lat:__previewMap.getCenter().lat, lng:__previewMap.getCenter().lng}));
    const settled = async () => {
        await page.waitForFunction(() => {
            const center = __previewMap.getCenter();
            const view = [center.lat, center.lng, __previewMap.getZoom()].join(',');
            const last = window.__previewViewSettled;
            window.__previewViewSettled = {view, frames: last?.view === view ? last.frames + 1 : 0};
            return !__previewMap._animatingZoom && !__previewMap._panAnim?._inProgress && window.__previewViewSettled.frames >= 8;
        });
        await page.evaluate(() => { delete window.__previewViewSettled; });
    };
    let watch = { running: true, ready: true, connected: true, transport: 'netsim', mac: 'C2:7A:4D:91:0B:68',
        binding_address: {value: 'C2:7A:4D:91:0B:68', medium: 'virtual'}, total_km: .8, pending: 3, received: 1, error: null,
        records: [1,2,3,4].map((d,i) => ({date:`2026-11-0${d}T07:00:00+08:00`,distance_km:.2,duration_seconds:90,received:i===0})) };
    let failed = false;
    await page.route('**/api/watch/status', route => failed ? route.abort() : route.fulfill({json:watch}));
    try {
        await page.goto(base + '/#generate');
        await page.waitForSelector('#template-choice option[value="__upload__"]', {state:'attached'});
        await page.waitForFunction(() => !document.querySelector('#preview-fit').disabled);
        await settled();
        const initial = await view();
        await page.locator('#preview-zoom-out').click();
        await page.waitForFunction(zoom => __previewMap.getZoom() < zoom, initial.zoom); await settled();
        assert.equal(new URL(page.url()).hash, '#generate');
        pass('zoom button changes the map without entering the editor');
        const beforeWheel = await view(), box = await page.locator('#preview-map').boundingBox();
        await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
        await page.mouse.wheel(0, -120);
        await page.waitForFunction(zoom => __previewMap.getZoom() > zoom, beforeWheel.zoom);
        await settled(); assert.equal(new URL(page.url()).hash, '#generate');
        pass('mouse wheel zooms the preview without navigation');
        const beforeDrag = await view();
        await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
        await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + 65, box.y + box.height / 2 + 35, {steps:10}); await page.mouse.up();
        await settled();
        assert.equal(new URL(page.url()).hash, '#generate');
        assert.notDeepEqual(await view(), beforeDrag);
        const afterDrag = await view(); await page.evaluate(() => TrackPreview.revalidate()); await settled();
        assert.deepEqual(await view(), afterDrag);
        pass('dragging and background refresh preserve the preview view');
        await page.locator('#preview-fit').click();
        await settled(); assert.deepEqual(await view(), initial);
        const first = await page.locator('#track-choice').inputValue();
        await page.locator('#preview-map').click({position:{x:box.width/2,y:box.height/2}});
        await page.waitForFunction(id => editingTrackId === id, first);
        assert.equal(new URL(page.url()).hash, '#tracks');
        pass('clicking the map enters the selected track editor');
        await page.locator('[data-nav="generate"]').click();
        const second = await page.locator('#track-choice option').nth(1).getAttribute('value');
        await page.locator('#track-choice').selectOption(second);
        await page.locator('#edit-preview-track').click();
        await page.waitForFunction(id => editingTrackId === id, second);
        pass('text entry switches the already-open editor to the newly selected track');
        await page.locator('[data-nav="generate"]').click();
        await page.locator('#track-choice').selectOption(first);
        await page.locator('#preview-map').focus(); await page.keyboard.press('Enter');
        await page.waitForFunction(id => editingTrackId === id, first);
        pass('keyboard entry opens the selected track');
        await page.locator('[data-nav="generate"]').click();
        await page.screenshot({path:path.join(output,'preview-desktop.png')});
        await page.locator('[data-nav="watch"]').click();
        await page.waitForFunction(() => document.querySelector('#watch-progress').value === 1);
        assert.equal(await page.locator('#watch-progress').getAttribute('max'), '4');
        assert.match(await page.locator('#watch-progress-text').innerText(), /1 \/ 4 · 25%/);
        await page.screenshot({path:path.join(output,'progress-partial.png')});
        pass('receipt progress reflects confirmed files');
        await page.locator('[data-filter="received"]').click();
        assert.match(await page.locator('#watch-progress-text').innerText(), /1 \/ 4 · 25%/);
        watch.records.forEach(r => { r.received = true; }); watch.pending = 0; watch.received = 4;
        await page.locator('#retry-status').evaluate(e => e.click());
        await page.waitForFunction(() => document.querySelector('#watch-progress').value === 4);
        assert.match(await page.locator('#watch-progress-text').innerText(), /100%/);
        pass('filtering keeps batch progress; completion reaches 100%');
        await page.screenshot({path:path.join(output,'progress-desktop.png')});
        failed = true; await page.locator('#retry-status').evaluate(e => e.click());
        await page.waitForFunction(() => document.querySelector('#watch-progress-wrap').classList.contains('is-stale'));
        assert.match(await page.locator('#watch-progress-text').innerText(), /上次确认/);
        assert.equal(await page.locator('#watch-progress').evaluate(e => e.value), 4);
        pass('read failure labels the retained last-confirmed progress');
        failed = false; watch.records = []; watch.pending = watch.received = watch.total_km = 0;
        await page.locator('#retry-status').click(); await page.waitForFunction(() => document.querySelector('#watch-progress-wrap').hidden);
        pass('empty batch hides the progress indicator');
        watch.records = [1,2,3,4].map(d=>({date:`2026-11-0${d}T07:00:00+08:00`,distance_km:.2,duration_seconds:90,received:false}));
        watch.pending = 4; watch.total_km = .8;
        await page.locator('#retry-status').evaluate(e => e.click());
        await page.waitForFunction(() => !document.querySelector('#watch-progress-wrap').hidden);
        assert.match(await page.locator('#watch-progress-text').innerText(), /0 \/ 4 · 0%/);
        await page.locator('[data-filter="all"]').click();
        await page.setViewportSize({width:390,height:844});
        assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),true);
        await page.screenshot({path:path.join(output,'progress-mobile.png'),fullPage:true});
        await page.locator('[data-nav="generate"]').click();
        await page.evaluate(() => scrollTo(0, 0));
        await page.screenshot({path:path.join(output,'preview-mobile.png'),fullPage:true});
        pass('pending and mobile states show compact controls without overflow');
        assert.deepEqual(errors, []);
    } finally {
        fs.writeFileSync(path.join(output,'results.json'),JSON.stringify({checks,errors},null,2));
        await browser.close();
    }
})().catch(error => { console.error(error); process.exitCode = 1; });
